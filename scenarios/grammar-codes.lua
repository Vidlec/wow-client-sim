-- The game's grammar code "|4singular:plural;" picks its form by the number before it, as the client draws it
-- (the death dialog's "%d |4Minute:Minutes;" showed the raw code before)
local frame = G.CreateFrame("Frame", nil, G.UIParent)
frame:SetSize(400, 100)
frame:SetPoint("CENTER")
local one = frame:CreateFontString(nil, "OVERLAY", "GameFontNormal")
one:SetPoint("TOP", 0, -10)
one:SetFormattedText("Release in %d |4Minute:Minutes;", 1)
local many = frame:CreateFontString(nil, "OVERLAY", "GameFontNormal")
many:SetPoint("TOP", 0, -40)
many:SetFormattedText("Release in %d |4Minute:Minutes; and %d |4Second:Seconds;", 6, 1)
wait(0.1)
expectText("Release in 1 Minute", "one: the singular")
expectText("Release in 6 Minutes and 1 Second", "each code by its own number")
expectNoText("|4", "no raw code is drawn")
